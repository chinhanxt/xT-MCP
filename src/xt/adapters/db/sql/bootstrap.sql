-- revision/updated_at cho CAS; chặn đổi tenant_id/id/created_at.
CREATE FUNCTION xt.row_touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.tenant_id IS DISTINCT FROM OLD.tenant_id OR NEW.id IS DISTINCT FROM OLD.id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.created_by IS DISTINCT FROM OLD.created_by THEN
      RAISE EXCEPTION 'không được đổi tenant_id/id/created_at/created_by' USING ERRCODE = 'check_violation',
        CONSTRAINT = 'xt_immutable_system_columns';
    END IF;
    NEW.revision := OLD.revision + 1;
    NEW.updated_at := clock_timestamp();
    NEW.updated_by := xt.actor();
  ELSE
    NEW.revision := 1;
    NEW.created_by := xt.actor();
  END IF;
  RETURN NEW;
END $$;
GRANT EXECUTE ON FUNCTION xt.row_touch() TO xt_app, xt_workflow;

