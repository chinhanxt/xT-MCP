-- Ngữ cảnh RBAC của backend xT: chỉ ghi được qua xt.set_context() (SECURITY DEFINER, chỉ xt_app),
-- khóa theo (pid backend, xid của transaction) => hết hiệu lực khi transaction kết thúc, và
-- set_config('xt.roles', …) của client KHÔNG có tác dụng vì policy không đọc GUC.
CREATE UNLOGGED TABLE xt_meta.session_ctx (
  pid             int PRIMARY KEY,
  xid             xid8 NOT NULL,
  tenant_id       uuid NOT NULL,
  actor_id        uuid,
  roles           text[] NOT NULL,
  team_ids        uuid[] NOT NULL,
  department_ids  uuid[] NOT NULL,
  effective_actor uuid,
  client_azp      text,
  trace_id        text
);
REVOKE ALL ON xt_meta.login_tenant, xt_meta.session_ctx FROM PUBLIC;

CREATE FUNCTION xt.set_context(t uuid, a uuid, r text[], teams uuid[], depts uuid[],
                               ea uuid, azp text, tr text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE x text;
BEGIN
  IF t IS NULL THEN RAISE EXCEPTION 'thiếu tenant'; END IF;
  FOREACH x IN ARRAY coalesce(r, '{}') LOOP
    IF x !~ '^[a-z][a-z0-9_]{0,62}$' THEN RAISE EXCEPTION 'tên vai trò không hợp lệ: %', x; END IF;
  END LOOP;
  INSERT INTO xt_meta.session_ctx AS c VALUES (pg_backend_pid(), pg_current_xact_id(), t, a,
         coalesce(r, '{}'), coalesce(teams, '{}'), coalesce(depts, '{}'), ea, azp, tr)
  ON CONFLICT (pid) DO UPDATE SET xid = EXCLUDED.xid, tenant_id = EXCLUDED.tenant_id,
     actor_id = EXCLUDED.actor_id, roles = EXCLUDED.roles, team_ids = EXCLUDED.team_ids,
     department_ids = EXCLUDED.department_ids, effective_actor = EXCLUDED.effective_actor,
     client_azp = EXCLUDED.client_azp, trace_id = EXCLUDED.trace_id;
  -- GUC chỉ để tương thích với module dùng current_setting('xt.tenant_id') (hàng đợi); policy của
  -- model engine KHÔNG đọc GUC.
  PERFORM set_config('xt.tenant_id', t::text, true);
END $$;

-- Ngữ cảnh hiệu lực: login đã gắn thì lấy từ login_tenant; ngược lại chỉ dòng session_ctx của đúng
-- backend + transaction hiện tại. Không có => NULL => mọi policy false (fail-closed).
CREATE FUNCTION xt.cur(OUT tenant_id uuid, OUT actor_id uuid, OUT roles text[], OUT team_ids uuid[],
                       OUT department_ids uuid[])
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
  SELECT l.tenant_id, l.actor_id, l.roles, l.team_ids, l.department_ids
    FROM xt_meta.login_tenant l WHERE l.login = session_user
  UNION ALL
  SELECT c.tenant_id, c.actor_id, c.roles, c.team_ids, c.department_ids
    FROM xt_meta.session_ctx c
   WHERE c.pid = pg_backend_pid() AND c.xid = pg_current_xact_id_if_assigned()
     AND NOT EXISTS (SELECT 1 FROM xt_meta.login_tenant l2 WHERE l2.login = session_user)
  LIMIT 1
$$;
CREATE FUNCTION xt.cur_meta(OUT effective_actor uuid, OUT client_azp text, OUT trace_id text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
  SELECT c.effective_actor, c.client_azp, c.trace_id FROM xt_meta.session_ctx c
   WHERE c.pid = pg_backend_pid() AND c.xid = pg_current_xact_id_if_assigned()
$$;
CREATE FUNCTION xt.tenant() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT (xt.cur()).tenant_id $$;
CREATE FUNCTION xt.actor() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT (xt.cur()).actor_id $$;
CREATE FUNCTION xt.has_role(r text) RETURNS boolean LANGUAGE sql STABLE AS
$$ SELECT coalesce(r = ANY ((xt.cur()).roles), false) $$;
CREATE FUNCTION xt.in_teams(t uuid) RETURNS boolean LANGUAGE sql STABLE AS
$$ SELECT coalesce(t = ANY ((xt.cur()).team_ids), false) $$;
CREATE FUNCTION xt.in_departments(d uuid) RETURNS boolean LANGUAGE sql STABLE AS
$$ SELECT coalesce(d = ANY ((xt.cur()).department_ids), false) $$;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA xt FROM PUBLIC;
GRANT EXECUTE ON FUNCTION xt.cur(), xt.cur_meta(), xt.tenant(), xt.actor(), xt.has_role(text),
