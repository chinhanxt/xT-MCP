-- Đầu chuỗi theo tenant: khóa dòng (FOR UPDATE) tuần tự hóa việc nối chuỗi. Ở READ COMMITTED
-- transaction sau chờ rồi đọc bản mới nhất; ở REPEATABLE READ/SERIALIZABLE nó gặp lỗi
-- serialization (thử lại) thay vì nối vào một prev đã cũ (chuỗi không bao giờ rẽ nhánh, AUD-05).
CREATE TABLE xt_audit.head (
  tenant_id uuid PRIMARY KEY,
  seq       bigint NOT NULL,
